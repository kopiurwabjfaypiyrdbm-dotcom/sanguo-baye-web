import { existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const project = resolve(root, 'godot');
const exactEngine = 'D:\\03_Godot\\01_Engine\\Godot_v4.7.1-stable_win64.exe';
const engine = process.env.GODOT_BIN || (existsSync(exactEngine) ? exactEngine : 'godot');
const runtime = resolve(project, '.godot/runtime-tactical-outcome');
const paths = { appData: resolve(runtime, 'appdata'), localAppData: resolve(runtime, 'localappdata'), xdgConfig: resolve(runtime, 'xdg-config'), xdgCache: resolve(runtime, 'xdg-cache'), xdgData: resolve(runtime, 'xdg-data') };
for (const path of Object.values(paths)) mkdirSync(path, { recursive: true });
const env = { ...process.env, APPDATA: paths.appData, LOCALAPPDATA: paths.localAppData, XDG_CONFIG_HOME: paths.xdgConfig, XDG_CACHE_HOME: paths.xdgCache, XDG_DATA_HOME: paths.xdgData };
const version = spawnSync(engine, ['--version'], { cwd: root, env, encoding: 'utf8', timeout: 60_000 });
const versionText = String(version.stdout ?? '').trim();
if (version.error || version.status !== 0 || !versionText.startsWith('4.7.1')) throw new Error(`Godot 4.7.1 is required: ${versionText || version.error?.message || String(version.stderr ?? '').trim()}`);
process.stdout.write(`[Godot tactical outcome] engine=${versionText}\n`);
const result = spawnSync(engine, ['--headless', '--path', project, '--script', 'res://tests/tactical_battle_outcome_runner.gd'], { cwd: root, env, encoding: 'utf8', timeout: 180_000 });
if (result.stdout) process.stdout.write(result.stdout);
if (result.stderr) process.stderr.write(result.stderr);
if (result.error || result.signal || result.status !== 0) throw new Error(`Godot tactical outcome verification failed: ${result.error?.message ?? result.signal ?? result.status}`);
